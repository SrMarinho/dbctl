# --- status -----------------------------------------------------------------


def test_status_shape(make_config, fake_psql, fake_compose, fake_run, monkeypatch) -> None:
    fake_psql.default = ""  # database does not exist
    monkeypatch.setattr("dbctl.commands.status.database_exists", lambda c, db: False)
