"""Unit tests for command orchestration (commands/*): flows, guards, precedence.

Regression anchors from the spec validation plan:
  V12  re-create refuses ("already exists - use 'dbctl reset'")
  V17  drop of a non-prefixed database is refused (double guard)
  V34  abort without confirmation (UserAbort, exit 130)
  V38  unuse removes the override / V39  create --use serves right away
"""

