def test_drop_aborts_without_confirmation(make_config) -> None:
    with pytest.raises(UserAbort):
        drop.run(make_config(), db="dev_x", ask=lambda m: False)


def test_drop_confirmed_drops(make_config, fake_psql, fake_compose, monkeypatch) -> None:
    fake_psql.default = ""
    fake_psql.on("SELECT 1 FROM pg_database", returns="1\n")
    monkeypatch.setattr("dbctl.commands.drop.filestore_remove", lambda c, db: None)
    result = drop.run(make_config(), db="dev_x", yes=True)
    assert result == {"db": "dev_x", "existed": True}
    drops = [c[-1] for c in fake_psql.calls if "DROP DATABASE" in c[-1]]
    assert drops and 'DROP DATABASE IF EXISTS "dev_x"' in drops[0]


def test_drop_stops_service_when_serving(make_config, fake_psql, fake_compose) -> None:
    fake_psql.on("SELECT 1 FROM pg_database", returns="1\n")
    cfg = make_config()
    # A real override on disk: the strategy's current_database() reads it.
    (cfg.project_root / "docker-compose.override.yaml").write_text(
        "# GENERATED BY dbctl - DO NOT EDIT\nservices:\n  web:\n"
        '    command: ["odoo", "-d", "dev_x", "--db-filter=^dev_x$"]\n',
        encoding="utf-8",
    )
    drop.run(cfg, db="dev_x", yes=True)
    # strategy.stop() -> compose stop, then unuse removes the override
    assert any("stop" in c for c in fake_compose.calls)
    assert not (cfg.project_root / cfg.strategy.override_file).exists()


